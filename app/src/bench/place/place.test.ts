import { Group, Mesh, Vector3 } from 'three';
import { bonesFromDisk } from '@/spine-3d/bones/bones-from-disk';
import { drawSpine } from '@/spine-3d/scene/drawn-spine';
import { modelSpine } from '@/spine-3d/scene/spine-model';
import { sceneLayer } from '@/spine-3d/scene/scene-layer';
import { drawPlacement } from './draw-placement';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { caseStore } from '@/case-state/case-store';
import { emptyCase } from '@/case-state/empty-case';
import { smallStory } from '@/engine-room/stand-in/small-story';
import { EngineFailure } from '@/engine-room/engine-client';
import { filmRecordFrom } from '@/open-and-save/film-record';
import { currentStep } from '@/view-state/current-step';
import { MADE_UP_CASE } from '@/spine-3d/made-up-case/made-up-case';
import { CANNOT_TELL_WORDS, LOOK_WORDS, PLACE_WORDS as W, lookWords } from '@/words/place';
import { layoutInput } from './layout-input';
import { placementFixture } from './placement-fixture.scenes';
import { countWords, filmSide, pedicleSentences, placementCounts, placementLooks, reviewItems } from './placement-view';
import { placementFailure } from './placement-failure';
import { placeDock } from './place-dock';
import { notePlacementShown, placeState, requestPlacement } from './place-state';
const actions = { back: vi.fn(), retry: vi.fn(), review: vi.fn(), sheet: vi.fn(), view: vi.fn() };

beforeEach(() => { caseStore.getState().apply([{kind:'open-case',case:emptyCase()}]); });
describe('a first placement', () => {
  it('adapts all films and the accepted fit, leaving personal facts absent', () => {
    const story = smallStory(), c = { ...emptyCase(), films: Object.values(story.films).map((f) => filmRecordFrom(f.facts)), marks: structuredClone(story.pass.marks) };
    const front = c.marks.find((m) => m.film === 'front'); if (front === undefined) throw new Error('front');
    front.naming.flags.push('estimated');
    const input = layoutInput(MADE_UP_CASE.fit, c);
    expect(input.fit).toBe(MADE_UP_CASE.fit);
    expect(input.child).toEqual({ ageYears: null, weightKg: null, activity: null });
    expect(input).toMatchObject({ naming: 'may-be-one-off', versions: 32, seed: 7, pedicleChildShare: null });
    expect(input.front?.marks.film).toBe('front');
    expect(input.bendLeft?.marks.film).toBe('bend-left');
    expect(input.bendRight?.marks.film).toBe('bend-right');
    front.naming.flags = []; front.naming.l5ConfirmedOn = null;
    expect(layoutInput(MADE_UP_CASE.fit, c).naming).toBe('may-be-one-off');
    front.naming.l5ConfirmedOn = 0;
    expect(layoutInput(MADE_UP_CASE.fit, c).naming).toBe('as-read');
    expect(layoutInput(MADE_UP_CASE.fit, emptyCase()).front).toBeNull();
  });
  it('counts each pedicle once, including looks on hooks and empty places, then ends and names', () => {
    const result = placementFixture(), first = result.layouts[0]; if (first === undefined) throw new Error('layout');
    const a = first.anchors[0]; if (a === undefined) throw new Error('anchor');
    a.looks.push('near-the-aorta');
    expect(placementCounts(result)).toEqual({ screws: 16, hooks: 1, empty: 3, looks: 9 });
    expect(countWords(result)).toBe('16 screws, 1 hook, 3 left empty.');
    expect(reviewItems(result).filter((i) => i.anchor === 0)).toHaveLength(1);
    expect(reviewItems(result).find((i) => i.id === 'upper')?.sentences[0]).toContain('T4 in 19 of 32 versions');
    result.cannotTell.find((r) => r.code === 'ends-unsettled')?.levels.push('L1');
    expect(reviewItems(result).filter((i) => i.id === 'upper' || i.id === 'lower')).toHaveLength(2);
    expect(reviewItems(result).find((i) => i.id === 'upper')?.sentences).toContain('Together, T4 to L1 holds in 14 of 32 versions.');
    result.upperEnds = []; result.lowerEnds = []; result.pairs = [];
    expect(reviewItems(result).find((i) => i.id === 'upper')?.sentences).toEqual(['The upper end is drawn at T4. '+CANNOT_TELL_WORDS['ends-unsettled']]);
    result.firstIsSketch = true;
    expect(reviewItems(result).some((i) => i.id === 'upper' || i.id === 'lower')).toBe(false);
  });
  it('has both wordings for every look and words for every cannot-tell code', () => {
    expect(Object.keys(LOOK_WORDS)).toHaveLength(7);
    for (const code of Object.keys(LOOK_WORDS) as (keyof typeof LOOK_WORDS)[]) {
      expect(lookWords(code, 'screw')).not.toBe('');
      expect(lookWords(code, 'hook')).not.toBe('');
      expect(lookWords(code, 'none')).toBe(lookWords(code, 'hook'));
    }
    expect(Object.keys(CANNOT_TELL_WORDS)).toHaveLength(14);
    expect(Object.values(CANNOT_TELL_WORDS).every((sentence) => sentence.endsWith('.'))).toBe(true);
    expect(lookWords('may-be-too-narrow', 'none')).toBe('This pedicle may be too narrow for a screw.');
    expect(lookWords('shorter-than-tables', 'hook')).not.toContain('is shown');
    expect(lookWords('shorter-than-tables', 'screw', 25, 25)).toContain('so the shortest is shown');
    expect(lookWords('shorter-than-tables', 'screw', 30, 25)).not.toContain('is shown');
    const a = placementFixture().layouts[0]?.anchors[0]; if (a === undefined) throw new Error('anchor');
    a.pedicle.outerWidthMm = null; a.looks = ['may-be-too-narrow', 'no-table-for-this-age'];
    expect(pedicleSentences(a)).toEqual([LOOK_WORDS['no-table-for-this-age']]);
  });
  it('names sides by the upright front film, including its assumed facing', () => {
    expect(filmSide('left', 'patient-left')).toBe('right'); expect(filmSide('right', 'patient-left')).toBe('left');
    expect(filmSide('left', 'patient-right')).toBe('left'); expect(filmSide('right', 'patient-right')).toBe('right');
  });
  it('separates absent placements, repeating refusals and retryable faults', () => {
    const fault = (code: ConstructorParameters<typeof EngineFailure>[0]['code'], detail: string | null = null) => new EngineFailure({ code, message: '', detail });
    expect(placementFailure(fault('pass-no-spine-found'))?.kind).toBe('refused');
    expect(placementFailure(fault('tool-refused', 'implant-layout-refused: instrumented-span-not-fitted'))).toMatchObject({ kind: 'refused', reason: W.refused });
    expect(placementFailure(fault('tool-refused'))?.kind).toBe('refused');
    expect(placementFailure(fault('case-invalid-value'))?.kind).toBe('refused');
    expect(placementFailure(fault('engine-crashed'))?.kind).toBe('failed');
    expect(placementFailure(fault('engine-out-of-sync'))?.kind).toBe('refused');
    expect(placementFailure(fault('pass-cancelled'))).toBeNull();
  });
  it('offers only actions that work, with the dock words for each state', () => {
    const state = { ...placeState.getState(), phase: 'working' as const };
    expect(placeDock(state, actions)).toMatchObject({ sentence: W.working });
    expect(placeDock(state, actions).primary).toBeUndefined();
    expect(placeDock(state, actions).small).toBeUndefined();
    const ready = { ...state, phase: 'ready' as const, result: placementFixture() };
    const dock = placeDock(ready, actions);
    expect(dock.small).toBeUndefined();
    expect(dock.helper).toEqual({kind:'words', words:['16 screws, 1 hook, 3 left empty.']});
    expect(dock.sentence).toBe('A first placement: T4 to L1.'); expect(dock.quiet?.label).toBe('Review the 9'); expect(dock.primary).toBeUndefined();
    expect(placeDock({ ...ready, review: 1 }, actions).review?.count).toBe('2 of 9');
    const sketch = { ...ready.result, firstIsSketch: true, upperEnds: [], lowerEnds: [], pairs: [] };
    expect(placeDock({ ...ready, result: sketch }, actions).helper).toEqual({kind:'words',words:[W.sketch+' 16 screws, 1 hook, 3 left empty.']});
    expect(reviewItems(sketch).flatMap((item)=>item.sentences).join(' ')).not.toMatch(/Together,|holds in|upper end|lower end/);
    expect(placeDock({ ...state, phase: 'failed', failure: { kind: 'failed', reason: W.failed } }, actions).primary?.label).toBe(W.retry);
    expect(placeDock({ ...state, phase: 'failed', failure: { kind: 'refused', reason: W.refused } }, actions).primary).toBeUndefined();
    expect(placeDock({ ...ready, result: { ...ready.result, layouts: [] } }, actions).quiet?.label).toBe(W.backToThree);
  });
  it('draws no rod from a contoured line when its standing line was not given', () => {
    const result = placementFixture(), layout = result.layouts[0]; if (layout === undefined) throw new Error('layout');
    layout.rods.forEach((rod) => { rod.standingPointsMm = []; });
    expect(layout.rods.every((rod) => rod.pointsMm.length > 1)).toBe(true);
    const levels = MADE_UP_CASE.fit.vertebrae.map((v) => v.level);
    const root = new Group();
    const holders = new Map(levels.map((level) => { const group = new Group(); root.add(group); return [level, group] as const; }));
    const inside = sceneLayer(root, holders, () => undefined, () => undefined);
    const drawn = drawPlacement({ levels, addLayer: () => inside.layer }, MADE_UP_CASE.fit, layout, []);
    expect(inside.registrations().some((part) => part.id.startsWith('rod:'))).toBe(false);
    expect(inside.registrations().some((part) => part.id === 'anchor:0')).toBe(true);
    drawn.remove();
  });
  it('lifts shared looks once while keeping level-specific looks and side labels local', () => {
    const result = placementFixture(), layout = result.layouts[0]; if (layout === undefined) throw new Error('layout');
    layout.anchors.forEach((a) => { a.looks = ['direction-unreadable']; });
    const first = layout.anchors[0]; if (first === undefined) throw new Error('anchor');
    first.looks.push('near-the-aorta');
    expect(placementLooks(layout).shared).toEqual(['direction-unreadable']);
    const items = reviewItems(result);
    expect(items[0]).toMatchObject({id:'every-pedicle',label:'Every pedicle',levels:[],sentences:['The direction of the pedicles cannot be read from these films.']});
    expect(items.filter((item) => item.anchor !== null)).toHaveLength(1);
    expect(items.find((item) => item.anchor === 0)?.label).toBe('T4, right of the front film');
    expect(items.find((item) => item.id === 'names')?.label).toBe('Level names');
    layout.anchors.forEach((a) => { a.looks.push('near-the-aorta'); });
    expect(placementLooks(layout).shared).not.toContain('near-the-aorta');
    const change = result.namingScenarios[0]?.changes[0]; if (change === undefined) throw new Error('change');
    change.looksAdded = ['may-be-too-narrow','no-table-for-this-age'];
    const rows = reviewItems(result).find((item) => item.id === 'names')?.details?.[0]?.rows.join(' ');
    expect(rows).toContain('The published tables do not give what is needed to size this pedicle.');
    expect(rows).not.toContain('may be too narrow');
    expect(W.pedicle(4.587312904,6.918734)).toBe('Pedicle 4.5 to 7.0 mm, ');
    expect(W.size(4,25)).toBe('4.0 × 25 mm'); expect(W.diameter(5)).toBe('5.0 mm');
    expect(W.also([5,5.5,6],[27.5,30])).toBe('Also 5.0, 5.5, 6.0 mm wide and 27.5, 30 mm long in some versions.');
  });
  it('keys all layout inputs and carries a notice only across shown fits in one case', async () => {
    const story = smallStory(), c = {...emptyCase(),films:Object.values(story.films).map((f)=>filmRecordFrom(f.facts)),marks:structuredClone(story.pass.marks)};
    const engine = {proposeLayouts:vi.fn().mockResolvedValue(placementFixture())};
    const accepted = {key:'a',fit:MADE_UP_CASE.fit,bones:[],input:{} as never};
    await requestPlacement(engine,accepted,c); expect(placeState.getState().changed).toBe(false);
    placeState.setState({arriving:false}); notePlacementShown();
    const bends = c.marks.find((m)=>m.film==='bend-left')?.vertebrae[0]?.marks;
    if(bends?.kind !== 'bending') throw new Error('bending corners');
    bends.lines.sup[0].at[0] += 1;
    await requestPlacement(engine,accepted,c); expect(engine.proposeLayouts).toHaveBeenCalledTimes(2);
    expect(placeState.getState().changed).toBe(false);
    engine.proposeLayouts.mockRejectedValueOnce(new EngineFailure({code:'engine-crashed',message:'',detail:null}));
    await requestPlacement(engine,{...accepted,key:'b'},c);
    expect(placeState.getState()).toMatchObject({phase:'failed',changed:true});
    await requestPlacement(engine,{...accepted,key:'b'},c,true); expect(placeState.getState().changed).toBe(true);
    placeState.setState({arriving:false}); notePlacementShown(); currentStep.getState().go('three');
    await requestPlacement(engine,{...accepted,key:'b'},c); expect(placeState.getState().changed).toBe(false);
    caseStore.getState().apply([{kind:'open-case',case:c}]);
    await requestPlacement(engine,{...accepted,key:'c'},c); expect(placeState.getState().changed).toBe(false);
    await requestPlacement(engine,{...accepted,key:'d'},c); expect(placeState.getState().changed).toBe(false);
  });
  it('keeps an engine head at its entry and its tip forward and nearer the midline through a bone frame', () => {
    const scene = new Group(), model = modelSpine(MADE_UP_CASE.fit,bonesFromDisk());
    const inside = drawSpine(model,{scene,changed:vi.fn(),removed:vi.fn()});
    const layout = placementFixture().layouts[0], first = layout?.anchors[0]; if(layout===undefined||first===undefined)throw new Error('layout');
    const entry:[number,number,number]=[-78.7,-2.4,222.9], direction:[number,number,number]=[.871,-.409,.270], length=27.5;
    const drawn=drawPlacement(inside.spine,MADE_UP_CASE.fit,{...layout,upper:'T10',lower:'T11',anchors:[{...first,level:'T10',side:'left',kind:'screw',entryMm:entry,directionUnit:direction,lengthMm:length}],rods:[]},[]);
    scene.updateMatrixWorld(true);
    const group=inside.layers[0]?.registrations().find((r)=>r.id==='anchor:0')?.object;
    const shaft=group?.children[0], head=group?.children[1];if(!(shaft instanceof Mesh)||head===undefined)throw new Error('screw');
    const expectedHead=inside.spine.inScene(entry), actualHead=head.getWorldPosition(new Vector3()).toArray();
    actualHead.forEach((n,i)=>{expect(n).toBeCloseTo(expectedHead[i]??0,8);});
    const tip=shaft.localToWorld(new Vector3(0,length/2,0));
    const patientTip=new Vector3(...entry).addScaledVector(new Vector3(...direction).normalize(),length);
    const expectedTip=inside.spine.inScene(patientTip.toArray());tip.toArray().forEach((n,i)=>{expect(n).toBeCloseTo(expectedTip[i]??0,8);});
    expect(patientTip.x).toBeGreaterThan(entry[0]);expect(patientTip.y).toBeLessThan(entry[1]);
    expect(patientTip.x).toBeCloseTo(-54.73337950081357,8);
    expect(patientTip.y).toBeCloseTo(-13.654130636242536,8);
    drawn.remove();inside.spine.remove();model.dispose();
  });
  it('keeps one answer per fitted spine and requests again for a new fit', async () => {
    placeState.setState({ key: null, phase: 'idle' });
    const proposeLayouts = vi.fn().mockResolvedValue(placementFixture());
    const accepted = { key: 'one', fit: MADE_UP_CASE.fit, bones: [], input: {} as never };
    await requestPlacement({ proposeLayouts }, accepted, emptyCase());
    await requestPlacement({ proposeLayouts }, accepted, emptyCase());
    placeState.setState({arriving:false}); notePlacementShown();
    const answer = placeState.getState().result;
    placeState.setState({ sheet: true, review: 0 }); currentStep.getState().go('three');
    expect(placeState.getState()).toMatchObject({ sheet: false, review: null, result: answer });
    await requestPlacement({ proposeLayouts }, accepted, emptyCase());
    expect(proposeLayouts).toHaveBeenCalledTimes(1);
    await requestPlacement({ proposeLayouts }, { ...accepted, key: 'two' }, emptyCase());
    expect(proposeLayouts).toHaveBeenCalledTimes(2); expect(placeState.getState().changed).toBe(true);
  });
});
