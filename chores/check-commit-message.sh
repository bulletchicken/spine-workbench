#!/usr/bin/env bash
# Checks one commit message, or a pull request body, against the house
# rules in CONTRIBUTING.md. The commit-msg hook and CI both run it.
#
#   check-commit-message.sh [--tree <rev>] <message-file>
#   check-commit-message.sh --body <body-file>
#
# A commit message needs:
# - a subject `type(scope): summary` of at most 72 characters, with no
#   full stop at the end. The type is one of feat, fix, refactor, perf,
#   test, docs, build, ci, chore, style. The scope is optional; when given
#   it is `deps` or a real folder: a top-level folder, an engine crate, an
#   area of app/src, or a step named without its number. Folders are
#   looked up in <rev>'s tree when --tree is given (CI), otherwise in the
#   index (the hook, where the folder may be new in this very commit);
# - a blank line after the subject, and body lines of at most 72
#   characters (a single word with no spaces, such as a long path, may run
#   longer);
# - one author: no Co-authored-by line anywhere, no trailers of any kind,
#   and no "Generated with" or "Generated by" footer.
#
# A pull request body needs only the last rule: no Co-authored-by line
# and no generated-by footer.
#
# Lines starting with `#` are comments git removes, so they are ignored,
# as is everything below git's scissors line.

set -euo pipefail

TYPES='feat|fix|refactor|perf|test|docs|build|ci|chore|style'
problems=()

usage() {
  echo "usage: $0 [--tree <rev>] <message-file> | --body <body-file>" >&2
  exit 2
}

mode=commit
tree=
case "${1:-}" in
  --body) mode=body; shift ;;
  --tree) tree="${2:-}"; [ -n "$tree" ] || usage; shift 2 ;;
esac
[ $# -eq 1 ] || usage
[ -r "$1" ] || { echo "cannot read $1" >&2; exit 2; }

# The message as git will store it: no carriage returns, no comment lines,
# nothing below the scissors (and, by $(...), no trailing blank lines).
message="$(tr -d '\r' < "$1" | sed -e '/^# -\{24\} >8 -\{24\}$/,$d' -e '/^#/d')"

# ---- One author, in commits and pull request bodies alike.

if printf '%s\n' "$message" | grep -Eiq '^[[:space:]]*co-authored-by[[:space:]]*:'; then
  problems+=("a Co-authored-by line: commits carry one author")
fi
if printf '%s\n' "$message" | grep -Eiq '^[^[:alnum:]]*generated (with|by)[[:space:]]'; then
  problems+=("a \"Generated with\" or \"Generated by\" footer: no tool footers")
fi

if [ "$mode" = commit ]; then
  subject="$(printf '%s\n' "$message" | sed -n 1p)"
  second="$(printf '%s\n' "$message" | sed -n 2p)"

  # ---- Subject shape.
  if [ -z "$subject" ]; then
    problems+=("the message is empty")
  elif ! printf '%s\n' "$subject" | grep -Eq "^($TYPES)(\([a-z0-9-]+\))?: [^ ]"; then
    problems+=("the subject must read \`type(scope): summary\` with type one of ${TYPES//|/, }: \"$subject\"")
  fi
  if [ "${#subject}" -gt 72 ]; then
    problems+=("the subject is ${#subject} characters; at most 72")
  fi
  case "$subject" in
    *.) problems+=("the subject ends with a full stop") ;;
  esac

  # ---- The scope names a real folder.
  scope="$(printf '%s\n' "$subject" | sed -nE "s/^($TYPES)\(([a-z0-9-]+)\):.*/\2/p")"
  if [ -n "$scope" ] && [ "$scope" != deps ]; then
    folder_exists() {
      if [ -n "$tree" ]; then
        [ "$(git cat-file -t "$tree:$1" 2>/dev/null)" = tree ]
      else
        [ -n "$(git ls-files --cached -- "$1/" | head -n 1)" ]
      fi
    }
    is_step() {
      if [ -n "$tree" ]; then
        git ls-tree --name-only "$tree:app/src/steps" 2>/dev/null | grep -Eq "^[0-9]-$scope\$"
      else
        git ls-files --cached -- app/src/steps/ | grep -Eq "^app/src/steps/[0-9]-$scope/"
      fi
    }
    if ! { folder_exists "$scope" || folder_exists "engine/$scope" || folder_exists "app/src/$scope" || is_step; }; then
      problems+=("the scope \"$scope\" is not deps, a top-level folder, an engine crate, an app/src area or a step")
    fi
  fi

  # ---- Body layout.
  if [ -n "$second" ]; then
    problems+=("the second line must be blank")
  fi
  long="$(printf '%s\n' "$message" | sed 1d | awk 'length > 72 && / / { print NR + 1 ": " $0 }')"
  if [ -n "$long" ]; then
    problems+=("body lines over 72 characters:
$long")
  fi

  # ---- No trailers of any kind.
  trailers="$(printf '%s\n' "$message" | git interpret-trailers --parse)"
  if [ -n "$trailers" ]; then
    problems+=("trailer lines: commits carry none:
$trailers")
  fi
fi

if [ "${#problems[@]}" -gt 0 ]; then
  what='commit message'
  [ "$mode" = body ] && what='pull request body'
  echo "This $what breaks the house rules (see CONTRIBUTING.md):" >&2
  for problem in "${problems[@]}"; do
    printf '  - %s\n' "$problem" >&2
  done
  exit 1
fi
