/// Writes one type and every type it uses.
type Export = fn(&Config) -> Result<(), ts_rs::ExportError>;

const TYPES_DIR: &str = "app/src/shapes/generated";
const SCHEMA_FILE: &str = "docs/contracts/case-file-v1.schema.json";
const CHECK_DIR: &str = "target/chores/shapes-check";
const NOTE: &str =
    "// Written by `cargo chores shapes` from engine/shapes. Do not edit this file by hand.\n";

pub fn run(root: &Path, check: bool) -> Outcome {
    if check {
        let scratch = root.join(CHECK_DIR);
        clear(&scratch)?;
        write_types(&scratch.join("types"))?;
        let mut differences = compare_folders(&scratch.join("types"), &root.join(TYPES_DIR))?;
        let committed_schema = fs::read_to_string(root.join(SCHEMA_FILE)).unwrap_or_default();
        if committed_schema != schema_text() {
            differences.push(format!("{SCHEMA_FILE} differs"));
        }
        if differences.is_empty() {
            println!("generated shapes match engine/shapes");
            Ok(())
        } else {
            Err(format!(
                "generated shapes are out of date (run `cargo chores shapes`):\n  {}",
                differences.join("\n  ")
            ))
        }
    } else {
        let types = root.join(TYPES_DIR);
        clear(&types)?;
        write_types(&types)?;
        let schema = root.join(SCHEMA_FILE);
        if let Some(folder) = schema.parent() {
            fs::create_dir_all(folder)
                .map_err(|error| format!("cannot create {folder:?}: {error}"))?;
        }
        fs::write(&schema, schema_text())
            .map_err(|error| format!("cannot write {SCHEMA_FILE}: {error}"))?;
        println!("wrote {TYPES_DIR}/ and {SCHEMA_FILE}");
        Ok(())
    }
}

/// Removes a generated folder and makes it again, empty, so a type that
/// was removed leaves no stale file behind.
fn clear(folder: &Path) -> Outcome {
    if folder.exists() {
        fs::remove_dir_all(folder).map_err(|error| format!("cannot clear {folder:?}: {error}"))?;
    }
    fs::create_dir_all(folder).map_err(|error| format!("cannot create {folder:?}: {error}"))
}

/// Every type the app imports, each with the types it uses. Each crosses
/// a boundary on its own: the case file, an export's input or output, a
/// worker message, or a list the app checks its own constants against.
fn write_types(folder: &Path) -> Outcome {
    let config = Config::new().with_out_dir(folder);
    let exports: [Export; 38] = [
        CaseFileV1::export_all,
        OpenedCase::export_all,
        EngineInfo::export_all,
        EngineError::export_all,
        FilmFacts::export_all,
        GeometryGuess::export_all,
        ScaleResult::export_all,
        AutoPassInput::export_all,
        AutoPassResult::export_all,
        FrontFinder::export_all,
        TrainedPassResult::export_all,
        FilmPassResult::export_all,
        ChainOptions::export_all,
        ChainAnswer::export_all,
        Step::export_all,
        WatchFrame::export_all,
        ToolPreviewInput::export_all,
        ToolPreview::export_all,
        RegionWandInput::export_all,
        RegionWandOutput::export_all,
        BoundaryWandInput::export_all,
        BoundaryWandOutput::export_all,
        PinInput::export_all,
        PinOutput::export_all,
        CheckFinding::export_all,
        MadeUpRecipe::export_all,
        AnswerKey::export_all,
        AnswerKeyComparison::export_all,
        MadeUpSpine::export_all,
        FitInput::export_all,
        SpineFit::export_all,
        FitFromFilms::export_all,
        MarkName::export_all,
        LandmarkName::export_all,
        Level::export_all,
        shapes::pixels::Px::export_all,
        ReadingsInput::export_all,
        SpineReadings::export_all,
    ];
    for export in exports {
        export(&config).map_err(|error| format!("cannot write the TypeScript shapes: {error}"))?;
    }

    let fingerprint = format!(
        "{NOTE}\n/** SHA-256 of the shapes crate's source. A worker whose engine reports a \
         different value is running a stale engine build. */\n\
         export const SHAPES_FINGERPRINT = \"{SHAPES_FINGERPRINT}\";\n"
    );
    let constants = format!(
        "{NOTE}\nimport type {{ Level }} from './Level';\n\
         import type {{ Template }} from './Template';\n\n\
         /** The value of `format` in every case file. */\n\
         export const CASE_FORMAT = \"{CASE_FORMAT}\";\n\n\
         /** The case file version this build writes, and the newest it reads. */\n\
         export const CASE_VERSION = {CASE_VERSION};\n\n\
         /** Confidence scores at or above this are high. */\n\
         export const CONFIDENCE_HIGH_FROM = {HIGH_FROM};\n\n\
         /** Confidence scores at or above this, and below the high band, are medium. */\n\
         export const CONFIDENCE_MEDIUM_FROM = {MEDIUM_FROM};\n\n\
         /** Every level, top to bottom. */\n\
         export const LEVELS: readonly Level[] = {levels};\n\n\
         /** Each vertebra count's levels, top to bottom, C7 included: the chain the auto pass solves. */\n\
         export const TEMPLATE_LEVELS: {{ readonly [T in Template]: readonly Level[] }} = {{\n{template_levels}}};\n\n\
         /**\n * Every name a vertebra on a film with each count can carry, top to bottom.\n * \
         Splits, merges and confirming L5 shift names along this list; a level\n * \
         outside `TEMPLATE_LEVELS` is flagged `non-standard-count`.\n */\n\
         export const TEMPLATE_NAMES: {{ readonly [T in Template]: readonly Level[] }} = {{\n{template_names}}};\n",
        levels = level_list(&Level::ALL),
        template_levels = template_table(Template::levels),
        template_names = template_table(Template::names),
    );
    for (name, text) in [("fingerprint.ts", fingerprint), ("constants.ts", constants)] {
        fs::write(folder.join(name), text)
            .map_err(|error| format!("cannot write {name}: {error}"))?;
    }
    Ok(())
}

/// Levels as a TypeScript array literal: `["C7", "T1"]`.
fn level_list(levels: &[Level]) -> String {
    let names: Vec<String> = levels
        .iter()
        .map(|level| format!("\"{}\"", level.name()))
        .collect();
    format!("[{}]", names.join(", "))
}

/// One line per template, `  'standard': [...],`, in declaration order.
fn template_table(levels_of: fn(Template) -> Vec<Level>) -> String {
    Template::ALL
        .iter()
        .map(|template| {
            let name = serde_json::to_string(template).expect("a template name serialises");
            format!("  {name}: {},\n", level_list(&levels_of(*template)))
        })
        .collect()
}

/// The JSON Schema of `case.json`, pretty-printed with a final newline.
///
/// schemars leaves `Option` fields out of `required`, but the strict reader
/// requires every field, `null` included, so every property of every
/// object is marked required here.
fn schema_text() -> String {
    let mut schema =
        serde_json::to_value(schemars::schema_for!(CaseFileV1)).expect("a JSON Schema is JSON");
    require_every_property(&mut schema);
    let mut text = serde_json::to_string_pretty(&schema).expect("a JSON value prints");
    text.push('\n');
    text
}

fn require_every_property(schema: &mut Value) {
    let Some(object) = schema.as_object_mut() else {
        return;
    };
    if let Some(Value::Object(properties)) = object.get("properties") {
        let names = properties.keys().cloned().map(Value::String).collect();
        object.insert("required".to_string(), Value::Array(names));
    }
    for (keyword, value) in object.iter_mut() {
        match keyword.as_str() {
            "properties" | "$defs" | "definitions" | "patternProperties" => {
                if let Some(children) = value.as_object_mut() {
                    children.values_mut().for_each(require_every_property);
                }
            }
            "allOf"
            | "anyOf"
            | "oneOf"
            | "prefixItems"
            | "items"
            | "additionalProperties"
            | "not"
            | "if"
            | "then"
            | "else"
            | "contains" => match value {
                Value::Array(children) => children.iter_mut().for_each(require_every_property),
                child => require_every_property(child),
            },
            _ => {}
        }
    }
}

/// What differs between a freshly generated folder and the committed one.
fn compare_folders(fresh: &Path, committed: &Path) -> Result<Vec<String>, String> {
    let fresh_names = file_names(fresh)?;
    let committed_names = file_names(committed).unwrap_or_default();
    let mut differences = Vec::new();
    for name in fresh_names.union(&committed_names) {
        let shown = format!("{TYPES_DIR}/{name}");
        match (fresh_names.contains(name), committed_names.contains(name)) {
            (true, false) => differences.push(format!("{shown} is missing")),
            (false, true) => differences.push(format!("{shown} should not exist")),
            _ => {
                let same = fs::read(fresh.join(name)).ok() == fs::read(committed.join(name)).ok();
                if !same {
                    differences.push(format!("{shown} differs"));
                }
            }
        }
    }
    Ok(differences)
}

fn file_names(folder: &Path) -> Result<BTreeSet<String>, String> {
    let entries =
        fs::read_dir(folder).map_err(|error| format!("cannot read {folder:?}: {error}"))?;
    entries
        .map(|entry| {
            entry
                .map(|entry| entry.file_name().to_string_lossy().into_owned())
                .map_err(|error| format!("cannot read {folder:?}: {error}"))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_case_file_property_is_required() {
        let schema: Value = serde_json::from_str(&schema_text()).expect("the schema is JSON");
        let film = &schema["$defs"]["FilmGeometry"];
        let required = film["required"].as_array().expect("required is listed");
        assert!(required.contains(&Value::from("mmPerPx")));
        assert!(required.contains(&Value::from("imageRight")));
        assert_eq!(
            required.len(),
            film["properties"].as_object().map_or(0, |p| p.len())
        );
    }

    #[test]
    fn required_reaches_into_every_keyword() {
        let mut schema = serde_json::json!({
            "oneOf": [{ "properties": { "a": {}, "b": { "items": { "properties": { "c": {} } } } } }]
        });
        require_every_property(&mut schema);
        assert_eq!(
            schema["oneOf"][0]["required"],
            serde_json::json!(["a", "b"])
        );
        assert_eq!(
            schema["oneOf"][0]["properties"]["b"]["items"]["required"],
            serde_json::json!(["c"])
        );
    }
}
