//! `cargo chores shapes [--check]`: everything generated from
//! `engine/shapes`, all committed:
//!
//! - `app/src/shapes/generated/`: one TypeScript file per shared type
//!   (from ts-rs), `fingerprint.ts` with the shapes fingerprint, and
//!   `constants.ts` with the values and lists the app and the engine must
//!   agree on (the case format, the confidence bands, the levels in order
//!   and each vertebra count's levels and names);
//! - `docs/contracts/case-file-v1.schema.json`: the JSON Schema of
//!   `case.json`.
//!
//! `--check` writes nothing in the repository: it generates into
//! `target/chores/shapes-check/` and fails if anything differs from what
//! is committed, so a shape changed without regenerating is caught.

